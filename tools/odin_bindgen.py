#!/usr/bin/env python3
"""Generate the Odin bindings for a Godot engine from its own API dumps.

Reads gdextension_interface.json and extension_api.json from an API directory (default: api/,
dumped by tools/dump_api.sh) and writes the generated files of gdextension/ and godot/. Generated
files start with "gen_" and are never edited by hand.

    tools/odin_bindgen.py            # api/
    tools/odin_bindgen.py path/to/api
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
NATIVE = ROOT
API = pathlib.Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else ROOT / "api"
HEADER = "// Generated by tools/odin_bindgen.py from the engine's API dumps. Do not edit.\n\n"

C_BASE = {
    "int8_t": "i8", "int16_t": "i16", "int32_t": "i32", "int64_t": "i64",
    "uint8_t": "u8", "uint16_t": "u16", "uint32_t": "u32", "uint64_t": "u64",
    "size_t": "uint", "float": "f32", "double": "f64",
    "char16_t": "u16", "char32_t": "rune", "wchar_t": "u32",
}
ODIN_KEYWORDS = {
    "align_of", "auto_cast", "bit_set", "break", "case", "cast", "context", "continue", "defer",
    "distinct", "do", "dynamic", "else", "enum", "fallthrough", "for", "foreign", "if", "import",
    "in", "map", "matrix", "not_in", "or_else", "or_return", "package", "proc", "return", "size_of",
    "struct", "switch", "transmute", "typeid", "union", "using", "when", "where", "string", "any",
    "type", "rawptr", "cstring", "bool", "int", "uint", "rune", "byte",
}


def ident(name):
    return name + "_" if name in ODIN_KEYWORDS else name


def gde_name(name):
    """GDExtensionVariantPtr -> VariantPtr, GDObjectInstanceID -> ObjectInstanceID."""
    for prefix in ("GDExtension", "GD"):
        if name.startswith(prefix) and len(name) > len(prefix) and name[len(prefix)].isupper():
            return name[len(prefix):]
    return name


class Interface:
    """The C interface: types, then one proc variable per interface function and a loader."""

    def __init__(self, data):
        self.data = data
        self.types = {t["name"]: t for t in data["types"]}

    def ctype(self, text):
        stars = text.count("*")
        base = re.sub(r"\bconst\b|\*", "", text).strip()
        if base == "void":
            return "^" * (stars - 1) + "rawptr" if stars else ""
        if base == "char":
            return "^" * (stars - 1) + "cstring" if stars else "u8"
        if base in C_BASE:
            odin = C_BASE[base]
        elif base in self.types:
            odin = gde_name(base)
        else:
            raise SystemExit(f"odin_bindgen: unknown C type {text!r}")
        if not stars:
            return odin
        # A pointer to a pointer-handle is an array of them (argument lists); index it.
        pointee = self.types.get(base, {})
        many = pointee.get("kind") == "handle" or odin in ("u8", "u16", "rune", "u32")
        return ("[^]" if many else "^") + "^" * (stars - 1) + odin

    def proc_type(self, item):
        args = []
        for i, arg in enumerate(item.get("arguments", [])):
            name = ident(arg.get("name") or f"arg{i}")
            args.append(f"{name}: {self.ctype(arg['type'])}")
        ret = self.ctype(item["return_value"]["type"]) if "return_value" in item else ""
        return f'proc "c" ({", ".join(args)})' + (f" -> {ret}" if ret else "")

    def enum(self, t):
        names = [v["name"] for v in t["values"]]
        prefix = names[0]
        for n in names[1:]:
            while not n.startswith(prefix):
                prefix = prefix[:-1]
        prefix = prefix[: prefix.rfind("_") + 1]
        name = gde_name(t["name"])
        if t.get("is_bitfield"):
            out = [f"{name} :: distinct u32"]
            out += [f"{v['name'][len(prefix):]} :: {name}({v['value']})" for v in t["values"]]
            return "\n".join(out) + "\n"
        out = [f"{name} :: enum i32 {{"]
        seen = set()
        for v in t["values"]:
            short = v["name"][len(prefix):]
            if short[0].isdigit():
                short = "_" + short
            if short not in seen:
                seen.add(short)
                out.append(f"\t{short} = {v['value']},")
        out.append("}")
        return "\n".join(out) + "\n"

    def emit(self):
        out = [HEADER, "package gdextension\n\n"]
        for t in self.data["types"]:
            name = gde_name(t["name"])
            kind = t["kind"]
            if kind == "enum":
                out.append(self.enum(t))
            elif kind == "handle":
                out.append(f"{name} :: rawptr\n")
            elif kind == "alias":
                out.append(f"{name} :: {self.ctype(t['type'])}\n")
            elif kind == "function":
                out.append(f"{name} :: {self.proc_type(t)}\n")
            elif kind == "struct":
                out.append(f"{name} :: struct {{\n")
                for m in t["members"]:
                    out.append(f"\t{ident(m['name'])}: {self.ctype(m['type'])},\n")
                out.append("}\n")
        out.append("\n")
        for item in self.data["interface"]:
            out.append(f"{ident(item['name'])}: {self.proc_type(item)}\n")
        out.append("\n// Fills every proc variable above from the engine's get_proc_address. A function this\n"
                   "// engine lacks stays nil.\n")
        out.append("load_interface :: proc(get_proc_address: InterfaceGetProcAddress) {\n")
        for item in self.data["interface"]:
            n = ident(item["name"])
            out.append(f'\t{n} = auto_cast get_proc_address("{item["name"]}")\n')
        out.append("}\n")
        return "".join(out)


def snake(name):
    """godot-cpp's rule: PhysicsServer3D -> physics_server3d, AABB -> aabb."""
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z\d])([A-Z])", r"\1_\2", name)
    return name.replace("2_D", "2D").replace("3_D", "3D").lower()


# The Variant type each builtin's name stands for, in the interface's VariantType enum.
VARIANT_TYPE = {
    "Nil": "NIL", "bool": "BOOL", "int": "INT", "float": "FLOAT", "String": "STRING",
    "Vector2": "VECTOR2", "Vector2i": "VECTOR2I", "Rect2": "RECT2", "Rect2i": "RECT2I",
    "Vector3": "VECTOR3", "Vector3i": "VECTOR3I", "Transform2D": "TRANSFORM2D",
    "Vector4": "VECTOR4", "Vector4i": "VECTOR4I", "Plane": "PLANE", "Quaternion": "QUATERNION",
    "AABB": "AABB", "Basis": "BASIS", "Transform3D": "TRANSFORM3D", "Projection": "PROJECTION",
    "Color": "COLOR", "StringName": "STRING_NAME", "NodePath": "NODE_PATH", "RID": "RID",
    "Object": "OBJECT", "Callable": "CALLABLE", "Signal": "SIGNAL", "Dictionary": "DICTIONARY",
    "Array": "ARRAY", "PackedByteArray": "PACKED_BYTE_ARRAY", "PackedInt32Array": "PACKED_INT32_ARRAY",
    "PackedInt64Array": "PACKED_INT64_ARRAY", "PackedFloat32Array": "PACKED_FLOAT32_ARRAY",
    "PackedFloat64Array": "PACKED_FLOAT64_ARRAY", "PackedStringArray": "PACKED_STRING_ARRAY",
    "PackedVector2Array": "PACKED_VECTOR2_ARRAY", "PackedVector3Array": "PACKED_VECTOR3_ARRAY",
    "PackedColorArray": "PACKED_COLOR_ARRAY", "PackedVector4Array": "PACKED_VECTOR4_ARRAY",
}
# Storage of a builtin's members, by the API's member meta.
MEMBER_META = {"float": "f32", "int32": "i32", "double": "f64", "int64": "i64"}
# Builtins passed to and from ptrcall as Odin scalars: ptrcall stores every int as 64 bits, every
# float as a double, a bool as one byte.
SCALAR = {"int": "i64", "float": "f64", "bool": "bool"}
CONFIG = "float_64"  # single-precision real_t, 64-bit pointers: this engine's build.


class Api:
    """Builtins, engine classes and singletons, as Odin types and ptrcall wrappers."""

    def __init__(self, data):
        self.data = data
        self.classes = {c["name"]: c for c in data["classes"]}
        self.builtins = {b["name"]: b for b in data["builtin_classes"]}
        self.sizes = next({s["name"]: s["size"] for s in c["sizes"]}
                          for c in data["builtin_class_sizes"] if c["build_configuration"] == CONFIG)
        self.members = next({k["name"]: k["members"] for k in c["classes"]}
                            for c in data["builtin_class_member_offsets"] if c["build_configuration"] == CONFIG)
        self.skipped = []

    # Types -----------------------------------------------------------------------------------

    def enum_type(self, ref):
        """enum::Node.ProcessMode -> Node_ProcessMode; enum::Error -> Error."""
        return ref.split("::", 1)[1].replace(".", "_")

    def odin_type(self, t):
        """The Odin type of an argument or return of type `t`, or None when it is not bound."""
        if t.startswith(("enum::", "bitfield::")):
            return self.enum_type(t)
        if t.startswith("typedarray::"):
            return "Array"
        if t.startswith("typeddictionary::"):
            return "Dictionary"
        if t in SCALAR:
            return SCALAR[t]
        if t in self.builtins or t == "Variant":
            return t
        if t in self.classes:
            return t
        if "*" in t:
            return "rawptr"
        return None

    def emit_enum(self, name, enum):
        values = enum["values"]
        if enum.get("is_bitfield"):
            out = [f"{name} :: distinct i64\n"]
            out += [f"{name}_{v['name']} :: {name}({v['value']})\n" for v in values]
            return "".join(out)
        out = [f"{name} :: enum i64 {{\n"]
        for v in values:
            out.append(f"\t{v['name']} = {v['value']},\n")
        return "".join(out) + "}\n"

    def emit_builtin_type(self, name):
        size = self.sizes[name]
        members = self.members.get(name)
        if members:
            out = [f"{name} :: struct {{\n"]
            for m in members:
                meta = MEMBER_META.get(m["meta"], m["meta"])
                out.append(f"\t{m['member']}: {meta},\n")
            out.append("}\n")
            out.append(f"#assert(size_of({name}) == {size})\n")
            out += [f"#assert(offset_of({name}, {m['member']}) == {m['offset']})\n" for m in members]
            return "".join(out)
        return f"{name} :: struct #align(8) {{ _opaque: [{size}]u8 }}\n"

    # Calls -----------------------------------------------------------------------------------

    def args_and_ptrs(self, arguments):
        """Odin parameters, locals that make each argument addressable, and the pointer array."""
        params, locals_, ptrs = [], [], []
        for a in arguments:
            t = self.odin_type(a["type"])
            n = ident(a["name"])
            params.append(f"{n}: {t}")
            if t == "bool":
                locals_.append(f"\t__a_{n} := u8({n})\n")
            elif t in self.classes:
                locals_.append(f"\t__a_{n} := rawptr({n})\n")
            else:
                locals_.append(f"\t__a_{n} := {n}\n")
            ptrs.append(f"&__a_{n}")
        return params, locals_, ptrs

    def call_body(self, call, ret_type, arguments):
        """The body of a wrapper: argument locals, the call into `call`, the return."""
        params, locals_, ptrs = self.args_and_ptrs(arguments)
        body = list(locals_)
        n = len(ptrs)
        args = f"&__args[0]" if n else "nil"
        if n:
            body.append(f"\t__args := [{n}]gde.ConstTypePtr{{{', '.join(ptrs)}}}\n")
        if not ret_type:
            body.append(f"\t{call.format(args=args, ret='nil')}\n")
        elif ret_type == "bool":
            body.append(f"\t__ret: u8\n\t{call.format(args=args, ret='&__ret')}\n\treturn __ret != 0\n")
        else:
            body.append(f"\t__ret: {ret_type}\n\t{call.format(args=args, ret='&__ret')}\n\treturn __ret\n")
        return params, "".join(body)

    def bindable(self, m):
        types = [a["type"] for a in m.get("arguments", [])]
        if "return_value" in m:
            types.append(m["return_value"]["type"])
        if "return_type" in m:
            types.append(m["return_type"])
        return all(self.odin_type(t) for t in types)

    def emit_class_method(self, cls, m):
        name = f"{snake(cls)}_{m['name']}"
        if m.get("is_vararg") or m.get("is_virtual") or not self.bindable(m):
            self.skipped.append(f"{cls}.{m['name']}")
            return ""
        ret = self.odin_type(m["return_value"]["type"]) if "return_value" in m else ""
        call = "gde.object_method_bind_ptrcall(__mb, " + ("nil" if m.get("is_static") else "rawptr(self)") + ", {args}, {ret})"
        params, body = self.call_body(call, ret, m.get("arguments", []))
        if not m.get("is_static"):
            params.insert(0, f"self: {cls}")
        sig = f'{name} :: proc "contextless" ({", ".join(params)})' + (f" -> {ret}" if ret else "")
        head = (f"\t@(static) __mb: gde.MethodBindPtr\n"
                f"\tif __mb == nil {{ __mb = method_bind(\"{cls}\", \"{m['name']}\", {m['hash']}) }}\n")
        # The engine returns a counted object as a Ref written into the slot, which holds a reference.
        owns = "// Owns a reference: release it.\n" if self.classes.get(ret, {}).get("is_refcounted") else ""
        return f"{owns}{sig} {{\n{head}{body}}}\n"

    def emit_builtin_method(self, bname, m):
        name = f"{snake(bname)}_{m['name']}"
        if m.get("is_vararg") or not self.bindable(m):
            self.skipped.append(f"{bname}.{m['name']}")
            return ""
        ret = self.odin_type(m["return_type"]) if "return_type" in m else ""
        base = "nil" if m.get("is_static") else "self"
        n = len(m.get("arguments", []))
        call = f"__fn({base}, {{args}}, {{ret}}, {n})"
        params, body = self.call_body(call, ret, m.get("arguments", []))
        if not m.get("is_static"):
            params.insert(0, f"self: ^{bname}")
        sig = f'{name} :: proc "contextless" ({", ".join(params)})' + (f" -> {ret}" if ret else "")
        vt = VARIANT_TYPE[bname]
        head = (f"\t@(static) __fn: gde.PtrBuiltInMethod\n"
                f"\tif __fn == nil {{ __fn = builtin_method(.{vt}, \"{m['name']}\", {m['hash']}) }}\n")
        return f"{sig} {{\n{head}{body}}}\n"

    def emit_builtin_lifetime(self, bname, b):
        """Constructors by index and the destructor of a builtin with one."""
        vt = VARIANT_TYPE[bname]
        out = []
        for ctor in b.get("constructors", []):
            args = ctor.get("arguments", [])
            if not all(self.odin_type(a["type"]) for a in args):
                continue
            suffix = "_from_" + "_".join(snake(a["type"]) for a in args) if args else ""
            name = f"{snake(bname)}_new{suffix}"
            params, locals_, ptrs = self.args_and_ptrs(args)
            n = len(ptrs)
            body = "".join(locals_)
            if n:
                body += f"\t__args := [{n}]gde.ConstTypePtr{{{', '.join(ptrs)}}}\n"
            out.append(
                f'{name} :: proc "contextless" ({", ".join(params)}) -> (__r: {bname}) {{\n'
                f"\t@(static) __fn: gde.PtrConstructor\n"
                f"\tif __fn == nil {{ __fn = gde.variant_get_ptr_constructor(.{vt}, {ctor['index']}) }}\n"
                f"{body}\t__fn(&__r, {'&__args[0]' if n else 'nil'})\n\treturn\n}}\n")
        if b.get("has_destructor"):
            out.append(
                f'{snake(bname)}_destroy :: proc "contextless" (self: ^{bname}) {{\n'
                f"\t@(static) __fn: gde.PtrDestructor\n"
                f"\tif __fn == nil {{ __fn = gde.variant_get_ptr_destructor(.{vt}) }}\n"
                f"\t__fn(self)\n}}\n")
        return "".join(out)

    # Files -----------------------------------------------------------------------------------

    def emit_types(self):
        out = [HEADER, "package godot\n\n"]
        for e in self.data["global_enums"]:
            out.append(self.emit_enum(e["name"].replace(".", "_"), e))
        for name, b in self.builtins.items():
            if name in SCALAR or name == "Nil":
                continue
            out.append(self.emit_builtin_type(name))
            for e in b.get("enums", []):
                out.append(self.emit_enum(f"{name}_{e['name']}", e))
        out.append("Variant :: struct #align(8) { _opaque: [%d]u8 }\n" % self.sizes["Variant"])
        for name, c in self.classes.items():
            out.append(f"{name} :: distinct rawptr\n")
            for e in c.get("enums", []):
                out.append(self.emit_enum(f"{name}_{e['name']}", e))
        return "".join(out)

    def emit_builtin_procs(self):
        out = [HEADER, "package godot\n\nimport gde \"../gdextension\"\n\n"]
        for name, b in self.builtins.items():
            if name in SCALAR or name == "Nil":
                continue
            out.append(self.emit_builtin_lifetime(name, b))
            for m in b.get("methods", []):
                out.append(self.emit_builtin_method(name, m))
        return "".join(out)

    def emit_utility_function(self, f):
        """One global utility function as `utility_<name>`, the prefix keeping Odin's own min, max,
        abs and clamp in scope. A vararg one takes its fixed arguments, then `rest`."""
        ret = self.odin_type(f["return_type"]) if "return_type" in f else ""
        arguments = f.get("arguments", [])
        fixed = len(arguments)
        head = (f"\t@(static) __fn: gde.PtrUtilityFunction\n"
                f"\tif __fn == nil {{ __fn = utility_function(\"{f['name']}\", {f['hash']}) }}\n")
        if not f.get("is_vararg"):
            call = f"__fn({{ret}}, {{args}}, {fixed})"
            params, body = self.call_body(call, ret, arguments)
        else:
            params, locals_, ptrs = self.args_and_ptrs(arguments)
            params.append("rest: ..Variant")
            body = "".join(locals_)
            body += f"\t__args: [{MOST_VARARGS}]gde.ConstTypePtr\n"
            body += "".join(f"\t__args[{i}] = {ptr}\n" for i, ptr in enumerate(ptrs))
            body += (f"\tif len(rest) > {MOST_VARARGS - fixed} {{ fail(\"odin: too many arguments\", \"{f['name']}\") }}\n"
                     f"\tfor i in 0 ..< len(rest) {{ __args[{fixed} + i] = &rest[i] }}\n")
            count = f"i32({fixed} + len(rest))"
            if ret:
                body += f"\t__ret: {ret}\n\t__fn(&__ret, &__args[0], {count})\n\treturn __ret\n"
            else:
                body += f"\t__fn(nil, &__args[0], {count})\n"
        sig = f'utility_{f["name"]} :: proc "contextless" ({", ".join(params)})' + (f" -> {ret}" if ret else "")
        return f"{sig} {{\n{head}{body}}}\n"

    def emit_utility_procs(self):
        out = [HEADER, "package godot\n\nimport gde \"../gdextension\"\n\n"]
        for f in self.data["utility_functions"]:
            if not self.bindable(f):
                raise SystemExit(f"odin_bindgen: utility function {f['name']} has an unbound type")
            out.append(self.emit_utility_function(f))
        return "".join(out)

    def emit_class_procs(self):
        out = [HEADER, "package godot\n\nimport gde \"../gdextension\"\n\n"]
        for name, c in self.classes.items():
            for m in c.get("methods", []):
                out.append(self.emit_class_method(name, m))
        for s in self.data["singletons"]:
            out.append(
                f'{snake(s["name"])}_singleton :: proc "contextless" () -> {s["type"]} {{\n'
                f"\t@(static) __s: {s['type']}\n"
                f"\tif __s == nil {{ __s = {s['type']}(singleton(\"{s['name']}\")) }}\n"
                f"\treturn __s\n}}\n")
        return "".join(out)

# Most arguments one vararg utility call may pass, fixed ones included.
MOST_VARARGS = 32

# Most parameters a registered method may take, self included; godot/class.odin MAX_ARGS is one less.
MOST_PARAMS = 14


def emit_calls():
    """invoke_ret / invoke_void: call a proc with each parameter fetched by `arg`, one branch per arity.
    Odin has no parameter-pack expansion, so godot/class.odin dispatches through these."""
    def chain(ret):
        lines = []
        for n in range(MOST_PARAMS + 1):
            args = ", ".join(f"arg(intrinsics.type_proc_parameter_type(P, {i}), {i}, SELF, PTR, c)" for i in range(n))
            lead = "\twhen" if n == 0 else "\t} else when"
            lines.append(f"{lead} N == {n} {{")
            lines.append(f"\t\t{'return ' if ret else ''}f({args})")
        lines.append('\t} else {\n\t\t#panic("godot_odin: too many parameters")\n\t}')
        return "\n".join(lines)
    out = [HEADER, "package godot\n\nimport \"base:intrinsics\"\n\n"]
    out.append("// Calls `f` with its parameters read from `c` by `arg`; returns what `f` returns, of type `R`.\n")
    out.append("@(private)\ninvoke_ret :: #force_inline proc(f: $P, $R: typeid, $SELF, $PTR: bool, c: ^Call) "
               "-> R {\n\tN :: intrinsics.type_proc_parameter_count(P)\n")
    out.append(chain(True) + "\n}\n\n")
    out.append("// Calls `f`, which returns nothing, with its parameters read from `c` by `arg`.\n")
    out.append("@(private)\ninvoke_void :: #force_inline proc(f: $P, $SELF, $PTR: bool, c: ^Call) {\n"
               "\tN :: intrinsics.type_proc_parameter_count(P)\n")
    out.append(chain(False) + "\n}\n\n")
    out.append("// Describes each parameter of `P` from index `FIRST` on into `d`, by `describe_param`.\n")
    out.append("@(private)\ndescribe_params :: proc($P: typeid, $FIRST: int, d: ^Params) {\n"
               "\tN :: intrinsics.type_proc_parameter_count(P)\n")
    for k in range(MOST_PARAMS - 1):
        out.append(f"\twhen N > FIRST + {k} {{ describe_param(intrinsics.type_proc_parameter_type(P, FIRST + {k}), {k}, d) }}\n")
    out.append("}\n")
    return "".join(out)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text() == text:
        return
    path.write_text(text)
    print(f"odin_bindgen: wrote {path.relative_to(ROOT)}")


def main():
    interface = json.loads((API / "gdextension_interface.json").read_text())
    write(NATIVE / "gdextension" / "gen_interface.odin", Interface(interface).emit())
    api = Api(json.loads((API / "extension_api.json").read_text()))
    write(NATIVE / "godot" / "gen_types.odin", api.emit_types())
    write(NATIVE / "godot" / "gen_builtins.odin", api.emit_builtin_procs())
    write(NATIVE / "godot" / "gen_classes.odin", api.emit_class_procs())
    write(NATIVE / "godot" / "gen_utility.odin", api.emit_utility_procs())
    write(NATIVE / "godot" / "gen_calls.odin", emit_calls())
    write(NATIVE / "godot" / "gen_skipped.txt", "\n".join(api.skipped) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
